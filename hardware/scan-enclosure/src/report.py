"""Writes PARTS.md (parts, print time, filament, seams, fastener BOM) from build/build.json
and build/slice.json."""
import collections
import json
import os

import numpy as np

from build import parse
from sc import BUILD, ROOT

SLEEVES = ("Elegoo Anti-Vibration Feet for Centauri Carbon 2 Series (4 pcs), SKU GWCZ-EL-3DF-AC0325, "
           "https://eu.elegoo.com/products/anti-vibration-feet-for-centauri-carbon-2-4-pcs")


def hm(s):
    return f"{int(s // 3600)} h {int(s % 3600 // 60):02d} min"


def main():
    P, _ = parse()
    b = json.load(open(os.path.join(BUILD, "build.json")))
    sl = json.load(open(os.path.join(BUILD, "slice.json")))
    out = ["# Parts, seams and fasteners", "",
           f"Generated by `src/report.py`. Slicer: OrcaSlicer 2.5.0 CLI, `{sl['profile']['machine'][:-5]}`, "
           f"`{sl['profile']['process'][:-5]}` with {' '.join(sl['profile']['overrides'])}. "
           "Print each part alone, in the orientation of its STL, no supports. Times and grams are per piece.", "",
           "| part | qty | print size X x Y x Z (mm) | PETG time | PETG g | PLA Matte time | PLA Matte g |",
           "|---|---|---|---|---|---|---|"]
    tot = collections.Counter()
    for p in b["parts"]:
        r = sl["parts"][p["name"]]
        sz = " x ".join(f"{v:.0f}" for v in p["size"])
        out.append(f"| {p['name']} | {p['qty']} | {sz} | {hm(r['petg']['time_s'])} | {r['petg']['weight_g']:.0f} | "
                   f"{hm(r['pla_matte']['time_s'])} | {r['pla_matte']['weight_g']:.0f} |")
        for f in ("petg", "pla_matte"):
            tot[f + "_t"] += p["qty"] * r[f]["time_s"]
            tot[f + "_g"] += p["qty"] * r[f]["weight_g"]
    n = sum(p["qty"] for p in b["parts"])
    out.append(f"| **total ({n} pieces)** | | | **{hm(tot['petg_t'])}** | **{tot['petg_g']:.0f}** | "
               f"**{hm(tot['pla_matte_t'])}** | **{tot['pla_matte_g']:.0f}** |")
    # seams
    p2w = {p["name"]: np.array(p["p2w"]) for p in b["parts"]}
    js = b["joints"]
    out += ["", "## Seams", "",
            "Every insert is an M3 heat-set insert in a hole D4.0 x 6.7 (lead-in 0.2), boss D9, 1.5 mm floor. "
            "Insert axis vs the print layers of the insert part: perpendicular is best; parallel inserts get "
            "4 perimeters (see the README).", "",
            "| seam | parts | alignment | screws | max pitch (mm) | insert side | insert axis vs layers |",
            "|---|---|---|---|---|---|---|"]
    by = collections.defaultdict(list)
    for j in js:
        by[j["seam"]].append(j)
    for sid, lst in by.items():
        sc = [j for j in lst if j["kind"] != "dowel"]
        pts = np.array([j["p"] for j in sc])
        pitch = max(np.linalg.norm(np.diff(pts, axis=0), axis=1)) if len(pts) > 1 else 0
        ins = sc[0]["insert"]
        M = p2w.get(ins, p2w.get(ins.rsplit("_", 1)[0], np.eye(3, 4)))
        az = abs((M[:, :3].T @ np.array(sc[0]["a"]))[2])
        orient = "perpendicular" if az > 0.99 else "parallel"
        s = b["seams"][sid]
        dw = sum(1 for j in lst if j["kind"] == "dowel")
        al = s["alignment"] + (f" ({dw} dowels)" if dw and "dowel" not in s["alignment"] else "")
        out.append(f"| {sid} | {s['parts']} | {al} | {len(sc)} x M3x{sc[0]['screw']} | {pitch:.0f} | "
                   f"{s['insert_side']} | {orient} |")
    # BOM
    sc = [j for j in js if j["kind"] != "dowel"]
    by_len = collections.Counter(j["screw"] for j in sc)
    n_feet = sum(p["qty"] for p in b["parts"] if p["name"] == "foot_stub")
    out += ["", "## Fastener and hardware BOM", "", "| item | qty | where |", "|---|---|---|",
            f"| M3 heat-set insert (OD about 4.8, length 5.7) | {len(sc)} | every screw joint |"]
    for L in sorted(by_len):
        where = sorted({j["seam"].split("-")[0].replace("side_left_", "side_").replace("side_right_", "side_")
                        for j in sc if j["screw"] == L})
        out.append(f"| M3 x {L} socket head | {by_len[L]} | {', '.join(where)} |")
    out += [f"| M3 washer | {sum(1 for j in sc if j['kind'] == 'slot')} | cradle screws in the cheek arc slots |",
            f"| M3 nylon washer 0.8 mm | {sum(1 for j in sc if j['seam'] == 'bay-board')} | control board on its standoffs |",
            "| LED strips, TEPT5700 sensor, 60 x 40 perfboard, DC-022B jack, MTS-102 toggle, 16 mm pot, 3 mm LED | "
            "per electronics/DESIGN.md | channels at roof X +-90 and walls Y 95, sensor holder on side_left_front_lower, "
            "bay on base_rear, panel holes in back_lower |",
            "| 1/4\"-20 x 1/2\" (12.7 mm) screw + 1/4\" washer | 1 | cradle slot into the Quick Mount disc |",
            f"| {SLEEVES} | {(n_feet + 3) // 4} pack(s) | slipped over the {n_feet} printed foot stubs |",
            f"| printed dowel pins (on the base) | {sum(1 for j in js if j['kind'] == 'dowel')} | nothing to buy |"]
    with open(os.path.join(ROOT, "PARTS.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
